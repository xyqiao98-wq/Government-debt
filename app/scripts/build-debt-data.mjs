import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import XLSX from 'xlsx';

const appDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const sourceName = '【华泰固收】城投有息债务-20260630.xlsx';

export function extractCityDebt(workbook) {
  const rows = XLSX.utils.sheet_to_json(workbook.Sheets['统计（地市）'], { header: 1, defval: null, raw: true });
  const result = new Map();
  for (let col = 3; col < rows[0].length; col += 1) {
    const date = XLSX.SSF.parse_date_code(rows[0][col]);
    if (!date || date.m !== 12 || date.d !== 31) continue;
    for (const row of rows.slice(1)) {
      if (!row[1] || !row[2]) continue;
      const key = `${date.y}|${row[1]}|${row[2]}`;
      if (result.has(key)) throw new Error(`重复地市债务：${key}`);
      if (typeof row[col] === 'number' && Number.isFinite(row[col]) && row[col] >= 0) result.set(key, row[col]);
    }
  }
  return result;
}

export function extractDebtSeries(workbook) {
  const sheet = workbook.Sheets['统计（省份）'];
  if (!sheet) throw new Error('缺少统计（省份）工作表');
  const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: null, raw: true });
  const periods = {};
  for (let col = 2; col < rows[0].length; col += 1) {
    const date = XLSX.SSF.parse_date_code(rows[0][col]);
    if (!date) continue;
    if (date.y > 2025 || date.m !== 12 || date.d !== 31) continue;
    const period = `${date.y}-${String(date.m).padStart(2, '0')}-${String(date.d).padStart(2, '0')}`;
    const values = {};
    for (const row of rows.slice(1)) {
      if (!row[0]) continue; // Exclude total and growth rows.
      if (Object.hasOwn(values, row[0])) throw new Error(`重复省份：${row[0]}`);
      if (typeof row[col] !== 'number' || !Number.isFinite(row[col]) || row[col] < 0) throw new Error(`${period} ${row[0]} 债务无效`);
      values[row[0]] = row[col]; // Keep source precision; round only when displaying.
    }
    if (Object.keys(values).length !== 31) throw new Error(`${period} 省份数量不是31`);
    const total = rows.find(row => row[1] === '总计')?.[col];
    if (typeof total !== 'number' || Math.abs(Object.values(values).reduce((a, b) => a + b, 0) - total) > 0.01) throw new Error(`${period} 全国合计不平`);
    periods[period] = values;
  }
  if (!periods['2025-12-31']) throw new Error('缺少2025年末数据');
  return periods;
}

export function buildDebtData(workbookPath = path.resolve(appDir, '..', sourceName)) {
  const periods = extractDebtSeries(XLSX.readFile(workbookPath));
  const output = path.join(appDir, 'src', 'data', 'cityInvestmentDebt.ts');
  fs.writeFileSync(output, `// Generated by scripts/build-debt-data.mjs. Do not edit manually.\n// Source: ${sourceName}, 统计（省份）; 单位：亿元。\nexport const cityInvestmentDebtByPeriod: Record<string, Record<string, number>> = ${JSON.stringify(periods, null, 2)};\n`, 'utf8');
  console.log(`已生成 ${Object.keys(periods).length} 个年末时点、31省城投债务；2025-12-31 全国合计 ${Object.values(periods['2025-12-31']).reduce((a, b) => a + b, 0).toFixed(2)} 亿元。`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) buildDebtData(process.argv[2]);
